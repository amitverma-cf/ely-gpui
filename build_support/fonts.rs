use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::path::{Path, PathBuf};

use serde::Deserialize;

#[derive(Debug, Deserialize, Default)]
pub struct FontsConfig {
    pub sans: Option<FontEntry>,
    pub mono: Option<FontEntry>,
    #[serde(flatten)]
    pub groups: BTreeMap<String, FontEntry>,
}

#[derive(Debug, Deserialize, Default, Clone)]
pub struct FontEntry {
    pub family: Option<String>,
    pub files: Option<Vec<String>>,
}

pub fn generate_fonts(
    config: Option<&FontsConfig>,
    root_dir: &Path,
    assets_dir: &Path,
    out_dir: &Path,
) {
    let mut declared_files = BTreeSet::new();

    if let Some(cfg) = config {
        let mut add_entry = |entry: &FontEntry| {
            if let Some(files) = &entry.files {
                for file in files {
                    declared_files.insert(file.clone());
                }
            }
        };

        if let Some(sans) = &cfg.sans {
            add_entry(sans);
        }
        if let Some(mono) = &cfg.mono {
            add_entry(mono);
        }
        for (group_name, entry) in &cfg.groups {
            if group_name != "sans" && group_name != "mono" {
                add_entry(entry);
            }
        }
    }

    // Default to Inter and JetBrains Mono if nothing declared
    if declared_files.is_empty() {
        for file in [
            "fonts/Inter-Regular.ttf",
            "fonts/Inter-Medium.ttf",
            "fonts/Inter-SemiBold.ttf",
            "fonts/Inter-Italic.ttf",
            "fonts/JetBrainsMono-Regular.ttf",
            "fonts/JetBrainsMono-Medium.ttf",
            "fonts/ibm-plex-sans/IBMPlexSans-Regular.ttf",
        ] {
            declared_files.insert(file.to_string());
        }
    }

    let mut resolved_fonts: Vec<(String, PathBuf)> = Vec::new();

    for rel_path in &declared_files {
        let in_assets = assets_dir.join(rel_path);
        let in_root = root_dir.join(rel_path);
        let resolved = if in_assets.exists() {
            in_assets
        } else if in_root.exists() {
            in_root
        } else {
            panic!(
                "ely: Font file '{}' declared in ely-gpui.toml was not found on disk.\n\
                 Searched locations:\n\
                   - {}\n\
                   - {}\n\
                 Please verify the file exists or update your ely-gpui.toml [fonts] configuration.",
                rel_path,
                in_assets.display(),
                in_root.display()
            );
        };
        resolved_fonts.push((rel_path.clone(), resolved));
    }

    let mut code = String::new();
    code.push_str("// Generated by build_support/fonts.rs. Do not edit.\n\n");

    code.push_str("pub const EMBEDDED_FONTS: &[&[u8]] = &[\n");
    for (_, abs_path) in &resolved_fonts {
        let normalized = abs_path.to_string_lossy().replace('\\', "/");
        code.push_str(&format!("    include_bytes!(r\"{}\"),\n", normalized));
    }
    code.push_str("];\n\n");

    code.push_str("pub const FONT_NAMES: &[&str] = &[\n");
    for (rel_path, _) in &resolved_fonts {
        code.push_str(&format!("    \"{}\",\n", rel_path));
    }
    code.push_str("];\n\n");

    code.push_str("pub fn embedded_font(path: &str) -> Option<&'static [u8]> {\n");
    code.push_str("    match path {\n");
    for (rel_path, abs_path) in &resolved_fonts {
        let normalized = abs_path.to_string_lossy().replace('\\', "/");
        code.push_str(&format!(
            "        \"{}\" => Some(include_bytes!(r\"{}\")),\n",
            rel_path, normalized
        ));
    }
    code.push_str("        _ => None,\n");
    code.push_str("    }\n");
    code.push_str("}\n");

    let dest = out_dir.join("ely_fonts.rs");
    fs::write(dest, code).expect("failed to write ely_fonts.rs");
}
