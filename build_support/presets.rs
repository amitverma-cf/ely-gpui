use super::palette::PaletteColors;

pub fn get_preset_palettes(name: &str) -> (PaletteColors, PaletteColors) {
    let clean = name.to_ascii_lowercase().replace('_', "-");
    match clean.as_str() {
        "zinc" => (zinc_light(), zinc_dark()),
        "slate" => (slate_light(), slate_dark()),
        "nord" => (nord_light(), nord_dark()),
        "catppuccin" => (catppuccin_latte(), catppuccin_macchiato()),
        "tokyo-night" | "tokyonight" => (tokyo_day(), tokyo_storm()),
        _ => (
            super::palette::default_light_palette(),
            super::palette::default_dark_palette(),
        ),
    }
}

